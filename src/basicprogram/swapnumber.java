package basicprogram;

public class swapnumber {
    public static void main(String[] args) {
        int n1 = 6, n2 = 4;
        int t=0;
        System.out.print(n1);
        System.out.println(" " +n2);
        t = n1;
        n1 = n2;
        n2 = t;
        System.out.print(n1);
        System.out.print(n2);
    }
}
